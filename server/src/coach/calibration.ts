/**
 * Pro baselines from the averaged shot templates (scripts/calibrate-coach.ts writes
 * pro-baselines.generated.ts from this). Each template is weighted by shots_averaged;
 * low-confidence templates (fewer than 10 shots) count a quarter.
 */
import { CURVE_KEYS, RELEASE_METRIC_KEYS, type CurveKey, type ReleaseMetricKey } from '../cv/release.js';
import type { TemplateRecord } from '../cv/templates.js';

export const LOW_CONFIDENCE_WEIGHT = 0.25;
/** Floors so a near-constant metric or curve never produces huge z-scores. */
export const METRIC_SD_FLOOR: Record<ReleaseMetricKey, number> = {
  releaseElbowDeg: 3, setPointElbowDeg: 3, kneeDipDeg: 3, dipToReleaseMs: 33, releaseHeight: 0.01, trunkLeanDeg: 1,
  elbowFlare: 0.03, followThroughHoldMs: 33, pelvisRisePeak: 0.01, wristSnapDeg: 3, stanceWidth: 0.05, footTurnDeg: 2,
};
export const CURVE_SCALE_FLOOR: Record<CurveKey, number> = { elbow: 2, knee: 2, wristHeight: 0.01, pelvisRise: 0.01 };

export interface MetricBaseline {
  mean: number;
  sd: number;
  min: number;
  max: number;
  templates: number;
}
export interface ShotTypeBaseline {
  templates: number;
  shotsAveraged: number;
  metrics: Partial<Record<ReleaseMetricKey, MetricBaseline>>;
  /** Typical between-pro spread of each curve (weighted sd across templates, averaged over the grid). */
  curveScales: Record<CurveKey, number>;
}
export interface TemplateSummary {
  player: string;
  shotType: string;
  shootingHand: string;
  shotsAveraged: number;
  lowConfidence: boolean;
  uncertainDistance: boolean;
  weight: number;
}

const round = (v: number, d: number) => Number(v.toFixed(d));
const digits = (k: string) => (/Deg$|Ms$/.test(k) ? 1 : 3);
export const weightOf = (t: Pick<TemplateRecord, 'shotsAveraged' | 'lowConfidence'>) => t.shotsAveraged * (t.lowConfidence ? LOW_CONFIDENCE_WEIGHT : 1);

function weighted(values: { v: number; w: number }[]) {
  const W = values.reduce((a, x) => a + x.w, 0);
  const mean = values.reduce((a, x) => a + x.v * x.w, 0) / W;
  const variance = values.reduce((a, x) => a + x.w * (x.v - mean) ** 2, 0) / W;
  return { mean, sd: Math.sqrt(variance) };
}

export function calibrate(records: TemplateRecord[]): { baselines: Record<string, ShotTypeBaseline>; summary: TemplateSummary[] } {
  const sorted = [...records].sort((a, b) => (a.shotType + a.player < b.shotType + b.player ? -1 : 1));
  const baselines: Record<string, ShotTypeBaseline> = {};
  for (const type of [...new Set(sorted.map((r) => r.shotType))].sort()) {
    const rs = sorted.filter((r) => r.shotType === type);
    const metrics: ShotTypeBaseline['metrics'] = {};
    for (const k of RELEASE_METRIC_KEYS) {
      const vals = rs.flatMap((r) => (r.metrics[k] === null ? [] : [{ v: r.metrics[k]!, w: weightOf(r) }]));
      if (vals.length < 2) continue;
      const { mean, sd } = weighted(vals);
      const d = digits(k);
      metrics[k] = {
        mean: round(mean, d),
        sd: round(Math.max(sd, METRIC_SD_FLOOR[k]), d),
        min: round(Math.min(...vals.map((x) => x.v)), d),
        max: round(Math.max(...vals.map((x) => x.v)), d),
        templates: vals.length,
      };
    }
    const curveScales = {} as Record<CurveKey, number>;
    for (const c of CURVE_KEYS) {
      const sds: number[] = [];
      for (let f = 0; f < rs[0]!.curves[c].length; f++) {
        const vals = rs.flatMap((r) => (r.curves[c][f] === null ? [] : [{ v: r.curves[c][f]!, w: weightOf(r) }]));
        if (vals.length >= 2) sds.push(weighted(vals).sd);
      }
      const m = sds.reduce((a, b) => a + b, 0) / sds.length;
      curveScales[c] = round(Math.max(m, CURVE_SCALE_FLOOR[c]), c === 'elbow' || c === 'knee' ? 2 : 4);
    }
    baselines[type] = { templates: rs.length, shotsAveraged: rs.reduce((a, r) => a + r.shotsAveraged, 0), metrics, curveScales };
  }
  const summary = sorted.map((r) => ({
    player: r.player,
    shotType: r.shotType,
    shootingHand: r.shootingHand,
    shotsAveraged: r.shotsAveraged,
    lowConfidence: r.lowConfidence,
    uncertainDistance: r.uncertainDistance,
    weight: round(weightOf(r), 2),
  }));
  return { baselines, summary };
}

/** The generated TypeScript module, byte-for-byte deterministic. */
export function renderBaselinesModule(c: ReturnType<typeof calibrate>, sourceFiles: string[]): string {
  return `/**
 * GENERATED by \`npm run calibrate-coach -w server\` from ${sourceFiles.length} averaged pro shot templates
 * in server/reference-data/average-shots. Do not edit by hand; re-run the script after the data changes.
 * Weights: shots_averaged, low-confidence templates (fewer than 10 shots) × ${LOW_CONFIDENCE_WEIGHT}.
 */
import type { ShotTypeBaseline, TemplateSummary } from './calibration.js';

export const PRO_BASELINES: Record<string, ShotTypeBaseline> = ${JSON.stringify(c.baselines, null, 2)};

export const PRO_TEMPLATES: TemplateSummary[] = ${JSON.stringify(c.summary, null, 2)};
`;
}
